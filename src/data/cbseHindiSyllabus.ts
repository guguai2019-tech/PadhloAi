export function getAllowedMarksForCbseHindi(
  courseId: CbseHindiCourseId,
  format: CbseHindiPaperFormat,
): CbseHindiMarkOption[] {
  if (format === 'Full Hindi Question Paper') {
    return ['Official Blueprint Mix'];
  }
  if (format === 'MCQ Practice Test') {
    return ['MCQ'];
  }
  if (format === 'Reading Comprehension Practice') {
    return ['Official Blueprint Mix', 'MCQ', '1 Mark', '2 Marks'];
  }
  if (format === 'Grammar Practice') {
    if (courseId.startsWith('cbse-10')) {
      return ['Official Blueprint Mix', 'MCQ', '1 Mark', '2 Marks'];
    }
    return ['Official Blueprint Mix', 'MCQ', '1 Mark', '2 Marks', '3 Marks', '4 Marks'];
  }
  if (format === 'Writing Skills Practice') {
    if (courseId === 'cbse-10-hindi-a') {
      return ['Official Blueprint Mix', '4 Marks', '5 Marks', 'Long Answer'];
    }
    if (courseId === 'cbse-10-hindi-b') {
      return ['Official Blueprint Mix', '3 Marks', '4 Marks', '5 Marks', 'Long Answer'];
    }
    return ['Official Blueprint Mix', '3 Marks', '4 Marks', '5 Marks', 'Long Answer'];
  }
  if (format === 'Literature Practice') {
    return ['Official Blueprint Mix', 'MCQ', '2 Marks', '3 Marks', '4 Marks', '5 Marks', 'Long Answer'];
  }
  // Chapter-Wise / Topic-Wise
  return ['Official Blueprint Mix', 'MCQ', '1 Mark', '2 Marks', '3 Marks', '4 Marks', '5 Marks', 'Long Answer'];
}

export function buildCbseHindiCatalogSubjects(classLevel: CbseHindiClassLevel): SyllabusSubject[] {
  const courseIds: CbseHindiCourseId[] =
    classLevel === '10'
      ? ['cbse-10-hindi-a', 'cbse-10-hindi-b']
      : ['cbse-12-hindi-core', 'cbse-12-hindi-elective'];

  return courseIds.map((id) => {
    const meta = CBSE_HINDI_COURSES[id];
    return {
      name: meta.catalogSubjectName,
      code: meta.courseCode,
      subjectLanguage: 'Hindi',
      prescribedBooks: meta.prescribedBooks,
      chapters: meta.chapters,
    };
  });
}
